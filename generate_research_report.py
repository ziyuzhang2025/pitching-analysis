#!/usr/bin/env python3
"""Generate a local Markdown research report from validation harness outputs.

The report combines event-accuracy CSV data, pose reliability results, and an
optional robustness stress summary. It is deliberately conservative: all
metrics are reported as single-camera 2D video estimates, not 3D biomechanics.
"""

import argparse
import json
import statistics
from collections import Counter
from datetime import date
from pathlib import Path

import pandas as pd


EVENTS = [
    "front_foot_strike",
    "pelvis_peak",
    "trunk_peak",
    "ball_release",
]


def parse_args():
    """Parse research report options."""
    parser = argparse.ArgumentParser(
        description="Generate a local Markdown report from pitching harness outputs."
    )
    parser.add_argument(
        "--accuracy-csv",
        default="outputs/pitch_accuracy_evaluation.csv",
        help="CSV generated by evaluate_pitch_accuracy.py.",
    )
    parser.add_argument(
        "--reliability-csv",
        default=None,
        help="CSV generated by pose_reliability_harness.py.",
    )
    parser.add_argument(
        "--stress-summary-json",
        default=None,
        help="Optional JSON generated by robustness_stress_harness.py.",
    )
    parser.add_argument("--output-dir", default="outputs")
    parser.add_argument("--output-prefix", default="pitching_research_report")
    return parser.parse_args()


def safe_read_csv(path):
    """Return an empty DataFrame when an optional CSV is unavailable."""
    path = Path(path)
    return pd.read_csv(path) if path.exists() else pd.DataFrame()


def maybe_load_json(path):
    """Return None when an optional JSON artifact is unavailable."""
    if not path or not Path(path).exists():
        return None
    with Path(path).open("r", encoding="utf-8") as file:
        return json.load(file)


def percentage_within(errors, threshold):
    """Calculate the percentage of errors within a frame threshold."""
    if not errors:
        return None
    return 100.0 * sum(error <= threshold for error in errors) / len(errors)


def accuracy_rows(dataframe):
    """Return per-event accuracy statistics from the evaluator CSV."""
    rows = []
    for event in EVENTS:
        column = f"{event}_absolute_frame_error"
        if column not in dataframe.columns:
            rows.append({"event": event, "sample_count": 0})
            continue
        errors = [float(value) for value in dataframe[column].dropna().tolist()]
        rows.append(
            {
                "event": event,
                "sample_count": len(errors),
                "mean_absolute_frame_error": statistics.mean(errors) if errors else None,
                "median_absolute_frame_error": statistics.median(errors) if errors else None,
                "within_1_frame_pct": percentage_within(errors, 1),
                "within_3_frames_pct": percentage_within(errors, 3),
                "within_5_frames_pct": percentage_within(errors, 5),
            }
        )
    return rows


def markdown_table(rows, columns):
    """Build a compact Markdown table with N/A for missing values."""
    if not rows:
        return "No data available."
    lines = [
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join(["---"] * len(columns)) + " |",
    ]
    for row in rows:
        values = []
        for column in columns:
            value = row.get(column)
            if value is None or pd.isna(value):
                values.append("N/A")
            elif isinstance(value, float):
                if column in {"jitter", "dropout_rate"}:
                    values.append(f"{value:.3f}")
                else:
                    values.append(f"{value:.2f}")
            else:
                values.append(str(value).replace("|", "\\|"))
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def reliability_summary(dataframe):
    """Summarize review priority and risk reasons."""
    if dataframe.empty:
        return {"reports": 0, "priority_counts": {}, "reason_counts": {}}
    priorities = Counter(dataframe.get("review_priority", pd.Series(dtype=str)).dropna())
    reasons = Counter()
    if "risk_reasons" in dataframe.columns:
        for text in dataframe["risk_reasons"].dropna():
            reasons.update(str(text).split(";"))
    return {
        "reports": len(dataframe),
        "priority_counts": dict(priorities),
        "reason_counts": dict(reasons.most_common()),
    }


def build_markdown(accuracy, labeled_pitch_count, reliability, stress, source_paths):
    """Build a conservative, portfolio-ready local research report."""
    accuracy_table = markdown_table(
        accuracy,
        [
            "event",
            "sample_count",
            "mean_absolute_frame_error",
            "median_absolute_frame_error",
            "within_1_frame_pct",
            "within_3_frames_pct",
            "within_5_frames_pct",
        ],
    )
    lines = [
        "# Baseball Pitching Timing Analysis: Validation Report",
        "",
        f"Generated locally: {date.today().isoformat()}",
        "",
        "## Scope and Safety",
        "",
        (
            "This report evaluates a local, single-camera 2D pose analysis "
            "workflow. It is a video review aid, not a full 3D biomechanics "
            "assessment. Hip-shoulder separation, arm slot, and arm-trunk offset "
            "remain 2D camera-view proxies; this workflow does not estimate elbow "
            "force, injury risk, or true shoulder external rotation."
        ),
        "",
        "## Inputs",
        "",
        f"- Accuracy CSV: {source_paths['accuracy_csv']}",
        f"- Reliability CSV: {source_paths['reliability_csv'] or 'N/A'}",
        f"- Stress summary JSON: {source_paths['stress_summary_json'] or 'N/A'}",
        "",
        "## Event Accuracy",
        "",
        f"- Labeled pitches evaluated: {labeled_pitch_count}",
        "",
        accuracy_table,
        "",
        "Interpret frame errors in the context of video frame rate. At 30 fps, one frame is approximately 33.3 ms.",
        "",
        "## Pose Reliability and Review Queue",
        "",
        f"- Reports scanned: {reliability['reports']}",
        f"- Review priorities: {reliability['priority_counts'] or 'N/A'}",
        f"- Most common risk reasons: {reliability['reason_counts'] or 'N/A'}",
        "",
    ]
    if stress is None:
        lines.extend(["## Robustness Stress Test", "", "No stress summary was supplied.", ""])
    else:
        lines.extend(
            [
                "## Robustness Stress Test",
                "",
                f"- Source landmarks: {stress.get('source_landmarks', 'N/A')}",
                f"- Trials per condition: {stress.get('trials_per_condition', 'N/A')}",
                f"- Jitter levels: {stress.get('jitter_levels', 'N/A')}",
                f"- Dropout rates: {stress.get('dropout_rates', 'N/A')}",
                "",
                markdown_table(
                    stress.get('condition_summaries', []),
                    [
                        "event",
                        "jitter",
                        "dropout_rate",
                        "detected_fraction",
                        "mean_absolute_frame_shift",
                        "median_absolute_frame_shift",
                        "p90_absolute_frame_shift",
                    ],
                ),
                "",
            ]
        )
    lines.extend(
        [
            "## Interpretation",
            "",
            (
                "Use high-confidence results as efficient review starting points, "
                "not as definitive biomechanical conclusions. Visually confirm "
                "events flagged by the reliability harness, especially for 30 fps "
                "footage, ambiguous wrist peaks, poor landmark visibility, or peaks "
                "near search-window boundaries."
            ),
            "",
            "## Next Validation Step",
            "",
            (
                "Add independently labeled pitches from different videos, pitchers, "
                "camera angles, and frame rates. Re-run this report after every "
                "detector change to check for regression rather than optimizing only "
                "one familiar clip."
            ),
            "",
        ]
    )
    return "\n".join(lines)


def main():
    """Generate and save the local research report."""
    args = parse_args()
    accuracy = safe_read_csv(args.accuracy_csv)
    reliability = safe_read_csv(args.reliability_csv) if args.reliability_csv else pd.DataFrame()
    stress = maybe_load_json(args.stress_summary_json)
    accuracy_summary = accuracy_rows(accuracy)
    reliability_data = reliability_summary(reliability)
    source_paths = {
        "accuracy_csv": args.accuracy_csv,
        "reliability_csv": args.reliability_csv,
        "stress_summary_json": args.stress_summary_json,
    }
    markdown = build_markdown(
        accuracy_summary,
        len(accuracy),
        reliability_data,
        stress,
        source_paths,
    )

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    markdown_path = output_dir / f"{args.output_prefix}.md"
    summary_path = output_dir / f"{args.output_prefix}_summary.json"
    markdown_path.write_text(markdown, encoding="utf-8")
    summary_path.write_text(
        json.dumps(
            {
                "accuracy": accuracy_summary,
                "labeled_pitch_count": len(accuracy),
                "reliability": reliability_data,
                "stress_summary_included": stress is not None,
                "markdown_report": str(markdown_path),
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    print(f"Saved Markdown report: {markdown_path}")
    print(f"Saved report summary JSON: {summary_path}")


if __name__ == "__main__":
    main()
